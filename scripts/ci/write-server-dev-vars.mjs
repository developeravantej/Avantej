#!/usr/bin/env node
/**
 * Write apps/server/.dev.vars from process.env for CI (GitHub Actions).
 * Maps CI_* secret names to wrangler dev var names.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, "../../apps/server/.dev.vars");

const baseUrl = process.env.PLAYWRIGHT_BASE_URL ?? "http://localhost:3021";
const serverUrl =
	process.env.PLAYWRIGHT_SERVER_URL ?? "http://localhost:3020";

/** @type {Record<string, string | undefined>} */
const mapping = {
	DATABASE_URL: process.env.CI_DATABASE_URL ?? process.env.DATABASE_URL,
	TENANT_DATABASE_URL:
		process.env.CI_TENANT_DATABASE_URL ?? process.env.TENANT_DATABASE_URL,
	BETTER_AUTH_SECRET:
		process.env.CI_BETTER_AUTH_SECRET ??
		process.env.BETTER_AUTH_SECRET ??
		"ci-e2e-better-auth-secret-minimum-32-chars",
	BETTER_AUTH_URL: process.env.BETTER_AUTH_URL ?? serverUrl,
	CORS_ORIGIN: process.env.CORS_ORIGIN ?? baseUrl,
	WEB_APP_URL: process.env.WEB_APP_URL ?? baseUrl,
	ENCRYPTION_KEY: process.env.CI_ENCRYPTION_KEY ?? process.env.ENCRYPTION_KEY,
	NEON_API_KEY: process.env.NEON_API_KEY,
	STRIPE_SECRET_KEY: process.env.STRIPE_SECRET_KEY,
	STRIPE_PUBLISHABLE_KEY: process.env.STRIPE_PUBLISHABLE_KEY,
	STRIPE_WEBHOOK_SECRET: process.env.STRIPE_WEBHOOK_SECRET,
	RESEND_API_KEY: process.env.RESEND_API_KEY,
};

const required = ["DATABASE_URL", "ENCRYPTION_KEY"];
const missing = required.filter((k) => !mapping[k]?.trim());
if (missing.length > 0) {
	console.error(
		`write-server-dev-vars: missing required env: ${missing.join(", ")}`,
	);
	process.exit(1);
}

const lines = [
	"# Generated by scripts/ci/write-server-dev-vars.mjs — do not commit",
	"",
];
for (const [key, value] of Object.entries(mapping)) {
	if (value?.trim()) {
		lines.push(`${key}=${value.trim()}`);
	}
}

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, `${lines.join("\n")}\n`, "utf-8");
console.log(`Wrote ${outPath} (${lines.length - 2} vars)`);
