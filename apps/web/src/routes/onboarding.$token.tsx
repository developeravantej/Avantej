import { authClient } from "@/lib/auth-client";
import { client } from "@/utils/orpc";
import { useForm } from "@tanstack/react-form";
import { useQuery, useMutation } from "@tanstack/react-query";
import { createFileRoute, Link, useNavigate } from "@tanstack/react-router";
import { Loader2, MapPin, Building2, Smartphone } from "lucide-react";
import { toast } from "sonner";
import z from "zod";
import { Button } from "@/components/ui/button";
import {
	Card,
	CardContent,
	CardDescription,
	CardHeader,
	CardTitle,
} from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";

// Route is public — no _authenticated wrapper
// The routeTree type will be generated by TanStack Router devtools on first `bun dev:web` run.
export const Route = createFileRoute("/onboarding/$token")({
	component: OnboardingPage,
	validateSearch: z.object({ org: z.string().catch("") }),
});

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function isMobileDevice(): boolean {
	return /Android|iPhone|iPad|iPod|Opera Mini|IEMobile|WPDesktop/i.test(
		navigator.userAgent,
	);
}

function getPasswordStrength(password: string): {
	label: string;
	colorClass: string;
	widthClass: string;
} {
	if (password.length === 0)
		return { label: "", colorClass: "bg-transparent", widthClass: "w-0" };
	let score = 0;
	if (password.length >= 8) score++;
	if (/[A-Z]/.test(password)) score++;
	if (/[0-9]/.test(password)) score++;
	if (/[^A-Za-z0-9]/.test(password)) score++;
	if (score <= 1)
		return { label: "Weak", colorClass: "bg-red-400", widthClass: "w-1/4" };
	if (score === 2)
		return { label: "Fair", colorClass: "bg-yellow-400", widthClass: "w-2/4" };
	if (score === 3)
		return { label: "Good", colorClass: "bg-blue-400", widthClass: "w-3/4" };
	return { label: "Strong", colorClass: "bg-green-400", widthClass: "w-full" };
}

// ---------------------------------------------------------------------------
// Zod schemas (used for validation only — not passed directly to TanStack Form)
// ---------------------------------------------------------------------------

const fieldSchemas = {
	fullName: z.string().min(2, "Full name must be at least 2 characters"),
	email: z.string().email("Enter a valid email address"),
	password: z.string().min(8, "Password must be at least 8 characters"),
	phone: z.string().optional(),
};

// ---------------------------------------------------------------------------
// Page
// ---------------------------------------------------------------------------

function OnboardingPage() {
	// These are typed after routeTree regeneration; use search() with strict: false for now.
	const params = Route.useParams();
	const searchRaw = Route.useSearch();
	const token = (params as { token?: string }).token ?? "";
	const orgId = (searchRaw as { org?: string }).org ?? "";

	const navigate = useNavigate();

	// Detect mobile for universal-link banner
	const isMobile = isMobileDevice();
	const universalLink = `avantej://onboarding/${token}?org=${orgId}`;

	// Fetch invite context (public endpoint)
	const {
		data: context,
		isLoading: isLoadingContext,
		error: contextError,
	} = useQuery({
		queryKey: ["onboarding", "inviteContext", orgId, token],
		queryFn: () =>
			client.onboarding.getInviteContext({
				organizationId: orgId,
				token,
			}),
		enabled: !!orgId && !!token,
		retry: false,
	});

	// Redeem mutation
	const redeemMutation = useMutation({
		mutationFn: (vars: {
			fullName: string;
			email: string;
			password: string;
			phone?: string;
		}) =>
			client.onboarding.redeemInvite({
				organizationId: orgId,
				token,
				...vars,
			}),
		onSuccess: async () => {
			toast.success("Account created. Welcome!");
			// Better-Auth sets the session cookie in the response headers.
			// Calling getSession refreshes the client's in-memory session.
			await authClient.getSession();
			navigate({ to: "/dashboard" });
		},
		onError: (err: Error) => {
			const msg = err.message || "";
			if (
				msg.toLowerCase().includes("email") &&
				(msg.toLowerCase().includes("exist") ||
					msg.toLowerCase().includes("taken"))
			) {
				toast.error(
					"An account with this email already exists. Please log in instead.",
				);
			} else {
				toast.error(msg || "Something went wrong. Please try again.");
			}
		},
	});

	// TanStack Form
	const form = useForm({
		defaultValues: {
			fullName: "",
			email: "",
			password: "",
			phone: "",
		},
		onSubmit: async ({ value }) => {
			const result = fieldSchemas.fullName.safeParse(value.fullName);
			const emailResult = fieldSchemas.email.safeParse(value.email);
			const pwResult = fieldSchemas.password.safeParse(value.password);

			if (!result.success || !emailResult.success || !pwResult.success) {
				return;
			}

			redeemMutation.mutate({
				fullName: value.fullName,
				email: value.email,
				password: value.password,
				phone: value.phone || undefined,
			});
		},
	});

	// ── Guards ───────────────────────────────────────────────────────────────
	if (!orgId || !token) {
		return (
			<ErrorScreen message="This link appears to be invalid. Please ask reception for a new QR code." />
		);
	}

	if (isLoadingContext) {
		return (
			<div className="min-h-screen flex items-center justify-center bg-gray-50">
				<Loader2 className="h-8 w-8 animate-spin text-muted-foreground" />
			</div>
		);
	}

	// ── Error states ─────────────────────────────────────────────────────────
	if (contextError) {
		const errMsg = contextError instanceof Error ? contextError.message : "";
		const isExpiredOrGone =
			errMsg.toLowerCase().includes("not_found") ||
			errMsg.toLowerCase().includes("gone") ||
			errMsg.toLowerCase().includes("max") ||
			errMsg.toLowerCase().includes("expired") ||
			errMsg.toLowerCase().includes("inactive");

		return (
			<ErrorScreen
				message={
					isExpiredOrGone
						? "This code is no longer active — please ask reception for a new one."
						: "Unable to load this registration link. Please try again or ask reception for a new code."
				}
			/>
		);
	}

	if (!context) {
		return <ErrorScreen message="This registration link could not be found." />;
	}

	// ── Happy path: registration form ────────────────────────────────────────
	return (
		<div className="min-h-screen bg-gray-50 flex flex-col items-center justify-start py-10 px-4">
			{/* Mobile universal-link banner */}
			{isMobile && (
				<div className="w-full max-w-md mb-4">
					<div className="flex items-center justify-between rounded-xl border border-primary/20 bg-primary/5 px-4 py-3">
						<div className="flex items-center gap-2 text-sm">
							<Smartphone className="h-4 w-4 text-primary flex-shrink-0" />
							<span className="text-muted-foreground">
								Have the Avantej app?
							</span>
						</div>
						<a
							href={universalLink}
							className="text-sm font-medium text-primary underline-offset-2 hover:underline"
						>
							Open in app
						</a>
					</div>
				</div>
			)}

			<div className="w-full max-w-md space-y-4">
				{/* Branded welcome card */}
				<Card>
					<CardHeader className="text-center space-y-2 pb-3">
						{(context as { brandLogoUrl?: string }).brandLogoUrl && (
							<div className="flex justify-center mb-1">
								<img
									src={(context as { brandLogoUrl?: string }).brandLogoUrl}
									alt={(context as { orgName: string }).orgName}
									className="h-12 object-contain"
								/>
							</div>
						)}
						<CardTitle className="text-2xl">
							Welcome to {(context as { orgName: string }).orgName}
						</CardTitle>
						<CardDescription className="text-base flex flex-col items-center gap-1">
							<span className="flex items-center gap-1.5">
								<Building2 className="h-4 w-4 text-muted-foreground" />
								<span data-testid="onboarding-branch-name">
									{(context as { branchName: string }).branchName}
								</span>
							</span>
							{(context as { branchAddress?: string }).branchAddress && (
								<span className="flex items-center gap-1.5 text-sm text-muted-foreground">
									<MapPin className="h-3.5 w-3.5" />
									{(context as { branchAddress?: string }).branchAddress}
								</span>
							)}
						</CardDescription>
					</CardHeader>
				</Card>

				{/* Registration form */}
				<Card>
					<CardHeader className="pb-2">
						<CardTitle className="text-lg">Create your account</CardTitle>
						<CardDescription>
							Fill in the details below to register and get started.
						</CardDescription>
					</CardHeader>
					<CardContent>
						<form
							onSubmit={(e) => {
								e.preventDefault();
								e.stopPropagation();
								form.handleSubmit();
							}}
							className="space-y-4"
						>
							{/* Full name */}
							<form.Field
								name="fullName"
								validators={{
									onChange: ({ value }) => {
										const r = fieldSchemas.fullName.safeParse(value);
										return r.success
											? undefined
											: (r.error.issues[0]?.message ?? "Invalid");
									},
								}}
							>
								{(field) => (
									<div className="space-y-1.5">
										<Label htmlFor="fullName">Full Name</Label>
										<Input
											id="fullName"
											placeholder="e.g. Alex Johnson"
											value={field.state.value}
											onChange={(e) => field.handleChange(e.target.value)}
											onBlur={field.handleBlur}
											autoComplete="name"
											disabled={redeemMutation.isPending}
											data-testid="onboarding-name-input"
										/>
										{field.state.meta.isTouched &&
											field.state.meta.errors.length > 0 && (
												<p className="text-xs text-destructive">
													{String(field.state.meta.errors[0])}
												</p>
											)}
									</div>
								)}
							</form.Field>

							{/* Email */}
							<form.Field
								name="email"
								validators={{
									onChange: ({ value }) => {
										const r = fieldSchemas.email.safeParse(value);
										return r.success
											? undefined
											: (r.error.issues[0]?.message ?? "Invalid email");
									},
								}}
							>
								{(field) => (
									<div className="space-y-1.5">
										<Label htmlFor="email">Email Address</Label>
										<Input
											id="email"
											type="email"
											placeholder="you@example.com"
											value={field.state.value}
											onChange={(e) => field.handleChange(e.target.value)}
											onBlur={field.handleBlur}
											autoComplete="email"
											disabled={redeemMutation.isPending}
											data-testid="onboarding-email-input"
										/>
										{field.state.meta.isTouched &&
											field.state.meta.errors.length > 0 && (
												<p className="text-xs text-destructive">
													{String(field.state.meta.errors[0])}
												</p>
											)}
									</div>
								)}
							</form.Field>

							{/* Password */}
							<form.Field
								name="password"
								validators={{
									onChange: ({ value }) => {
										const r = fieldSchemas.password.safeParse(value);
										return r.success
											? undefined
											: (r.error.issues[0]?.message ?? "Invalid password");
									},
								}}
							>
								{(field) => {
									const strength = getPasswordStrength(field.state.value);
									return (
										<div className="space-y-1.5">
											<Label htmlFor="password">Password</Label>
											<Input
												id="password"
												type="password"
												placeholder="At least 8 characters"
												value={field.state.value}
												onChange={(e) => field.handleChange(e.target.value)}
												onBlur={field.handleBlur}
												autoComplete="new-password"
												disabled={redeemMutation.isPending}
												data-testid="onboarding-password-input"
											/>
											{field.state.value.length > 0 && (
												<div className="space-y-1">
													<div className="h-1 w-full rounded-full bg-gray-100 overflow-hidden">
														<div
															className={`h-full rounded-full transition-all duration-300 ${strength.colorClass} ${strength.widthClass}`}
														/>
													</div>
													{strength.label && (
														<p className="text-xs text-muted-foreground">
															Strength: {strength.label}
														</p>
													)}
												</div>
											)}
											{field.state.meta.isTouched &&
												field.state.meta.errors.length > 0 && (
													<p className="text-xs text-destructive">
														{String(field.state.meta.errors[0])}
													</p>
												)}
										</div>
									);
								}}
							</form.Field>

							{/* Phone (optional) */}
							<form.Field name="phone">
								{(field) => (
									<div className="space-y-1.5">
										<Label htmlFor="phone">
											Phone{" "}
											<span className="text-muted-foreground font-normal">
												(optional)
											</span>
										</Label>
										<Input
											id="phone"
											type="tel"
											placeholder="+60 12 345 6789"
											value={field.state.value}
											onChange={(e) => field.handleChange(e.target.value)}
											onBlur={field.handleBlur}
											autoComplete="tel"
											disabled={redeemMutation.isPending}
										/>
									</div>
								)}
							</form.Field>

							{/* Submit */}
							<Button
								type="submit"
								className="w-full"
								disabled={redeemMutation.isPending}
								data-testid="onboarding-submit-button"
							>
								{redeemMutation.isPending ? (
									<>
										<Loader2 className="mr-2 h-4 w-4 animate-spin" />
										Creating account...
									</>
								) : (
									"Create account"
								)}
							</Button>

							{/* Existing account hint */}
							<p className="text-center text-sm text-muted-foreground">
								Already have an account?{" "}
								<Link
									to="/login"
									search={{}}
									className="font-medium text-primary hover:underline underline-offset-2"
								>
									Log in instead
								</Link>
							</p>
						</form>
					</CardContent>
				</Card>
			</div>
		</div>
	);
}

// ---------------------------------------------------------------------------
// Error screen
// ---------------------------------------------------------------------------

function ErrorScreen({ message }: { message: string }) {
	return (
		<div className="min-h-screen flex items-center justify-center bg-gray-50 p-4">
			<Card className="w-full max-w-sm">
				<CardHeader>
					<CardTitle className="text-lg">Registration Unavailable</CardTitle>
					<CardDescription>{message}</CardDescription>
				</CardHeader>
				<CardContent>
					<p className="text-sm text-muted-foreground">
						If you need help, please speak to a member of staff at reception.
					</p>
				</CardContent>
			</Card>
		</div>
	);
}
