#!/usr/bin/env node
/**
 * Generates a DEDICATED Playwright config for the single-session audit-prove run.
 * Does NOT mutate the repo's own playwright.config.ts. Forces `video: "on"` so the
 * one continuous spec produces one .webm.
 *
 * All project specifics (baseURL, auth storageState, setup project, testDir, spec
 * name) come from the resolved config (--config) with per-flag overrides — nothing
 * is hardcoded to a particular repo. If no auth storageState is resolved, the
 * generated config has NO setup project and runs UNAUTHENTICATED.
 *
 * Usage:
 *   node scripts/gen-playwright-config.mjs --session <dir> [--config <file>]
 *     [--base-url <url>] [--auth <storageState.json>] [--setup-match <file.ts>]
 *     [--test-dir <dir>] [--spec-name <name>]
 *
 * Writes: <specName>.config.ts at the repo ROOT (default: gap-prove.config.ts).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const args = process.argv.slice(2);
const arg = (n, d = null) => {
	const i = args.indexOf(`--${n}`);
	return i >= 0 && args[i + 1] ? args[i + 1] : d;
};
const session = arg("session", null);
if (!session) {
	console.error("ERROR: --session <dir> is required");
	process.exit(1);
}

let cfg = {};
const configPath = arg("config", null);
if (configPath && existsSync(configPath)) {
	try {
		cfg = JSON.parse(readFileSync(configPath, "utf8"));
	} catch (e) {
		console.warn(`[gen] could not read --config ${configPath}: ${e.message}`);
	}
}
const e = cfg.e2e || {};

const baseURL = arg("base-url", e.baseURL || "http://localhost:3000");
const testDir = arg("test-dir", e.testDir || "e2e");
const authStorageState = arg("auth", e.authStorageState || null);
const setupTestMatch = arg("setup-match", e.setupTestMatch || null);
const specName = arg("spec-name", e.specName || "gap-prove");

const htmlOut = join(session, "test", "html").replace(/\\/g, "/");
const resultsJson = join(session, "test", "results.json").replace(/\\/g, "/");
mkdirSync(join(session, "test"), { recursive: true });

// regex literals for the generated file (escape dots -> literal `\.`)
const escDot = (s) => s.replace(/\./g, "\\.");
const specRe = `/${escDot(specName)}\\.spec\\.ts/`;
const setupRe = setupTestMatch ? `/${escDot(setupTestMatch)}/` : "/.*\\.setup\\.ts/";

const useAuth = !!authStorageState;
const projects = useAuth
	? `	projects: [
		{ name: "setup", testMatch: ${setupRe} },
		{
			name: ${JSON.stringify(specName)},
			use: { ...devices["Desktop Chrome"], storageState: AUTH_STATE },
			testMatch: ${specRe},
			dependencies: ["setup"],
		},
	],`
	: `	projects: [
		{
			name: ${JSON.stringify(specName)},
			use: { ...devices["Desktop Chrome"] },
			testMatch: ${specRe},
		},
	],`;

// NOTE: testDir is resolved RELATIVE TO THE CONFIG FILE'S DIRECTORY. We write the
// config at the repo ROOT and keep testDir repo-root-relative (e.g. "e2e"), so it
// resolves to <root>/e2e. Writing it inside e2e/ with testDir "e2e" would wrongly
// look in e2e/e2e/ and find no specs.
const config = `import { defineConfig, devices } from "@playwright/test";

// AUTO-GENERATED by /audit-prove — do not hand-edit; re-run gen-playwright-config.mjs.
// One continuous spec -> one video. Resilient: the spec uses expect.soft so a
// failing step records but the session keeps recording to the end.
const baseURL = process.env.PLAYWRIGHT_BASE_URL ?? ${JSON.stringify(baseURL)};
${useAuth ? `const AUTH_STATE = ${JSON.stringify(authStorageState)};\n` : ""}
export default defineConfig({
	testDir: ${JSON.stringify(testDir)},
	timeout: 300_000,            // long single session
	expect: { timeout: 10_000 },
	fullyParallel: false,
	workers: 1,
	reporter: [
		["list"],
		["html", { outputFolder: ${JSON.stringify(htmlOut)}, open: "never" }],
		["json", { outputFile: ${JSON.stringify(resultsJson)} }],   // <- the remediation loop reads this
	],
	use: {
		baseURL,
		video: "on",              // <- the whole point: always record
		trace: "on",
		screenshot: "only-on-failure",
	},
${projects}
});
`;

const out = `${specName}.config.ts`;
writeFileSync(out, config);
console.log(
	`[gen] wrote ${out} at repo root (baseURL=${baseURL}, testDir=${testDir}, video=on, auth=${useAuth ? authStorageState : "none — UNAUTHENTICATED"})`,
);
console.log(`[gen] author the spec at ${testDir}/${specName}.spec.ts, then run:`);
console.log(`[gen]   npx playwright test -c ${out}`);
console.log(`[gen] video lands in test-results/**/video.webm -> copy to ${session}/video/full-run.webm`);
